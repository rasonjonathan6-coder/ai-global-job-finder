package com.aiglobal.jobfinder.data.cv

import android.content.Context
import android.net.Uri
import android.provider.OpenableColumns
import com.aiglobal.jobfinder.data.model.CvFileType
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.IOException

/** A CV file that has been copied into app-private storage. */
data class StoredCvFile(
    override val displayName: String,
    val storedName: String,
    val fileType: CvFileType,
    override val sizeBytes: Long,
    val file: File,
) : CvSource {
    override fun openStream() = file.inputStream()
}

/**
 * Copies a picked document into the app's private files directory.
 *
 * Two things matter here. First, the file never leaves app-private storage, so no other
 * app can read the candidate's CV. Second, the stored name is generated by us from a
 * random UUID and a whitelisted extension: the original name is kept only as a display
 * label, so a hostile file name cannot influence a path on disk.
 */
class CvFileStore(private val context: Context) {

    private val directory: File
        get() = File(context.filesDir, DIRECTORY).apply { if (!exists()) mkdirs() }

    /**
     * Reads the picker metadata, validates type and size, then copies the bytes in.
     *
     * @throws CvImportException when the document cannot be accepted.
     */
    suspend fun import(uri: Uri): StoredCvFile = withContext(Dispatchers.IO) {
        val metadata = readMetadata(uri)
        val displayName = metadata.first
        val declaredSize = metadata.second
        val mimeType = context.contentResolver.getType(uri)

        val fileType = CvFileType.resolve(displayName, mimeType)
            ?: throw CvImportException.UnsupportedFormat(displayName)

        if (declaredSize > MAX_BYTES) throw CvImportException.TooLarge(declaredSize, MAX_BYTES)

        val storedName = "${java.util.UUID.randomUUID()}.${fileType.extensions.first()}"
        val target = File(directory, storedName)

        val copied = try {
            context.contentResolver.openInputStream(uri)?.use { input ->
                target.outputStream().use { output ->
                    val buffer = ByteArray(16 * 1024)
                    var total = 0L
                    while (true) {
                        val read = input.read(buffer)
                        if (read < 0) break
                        total += read
                        if (total > MAX_BYTES) {
                            target.delete()
                            throw CvImportException.TooLarge(total, MAX_BYTES)
                        }
                        output.write(buffer, 0, read)
                    }
                    total
                }
            } ?: throw CvImportException.Unreadable()
        } catch (e: IOException) {
            target.delete()
            throw CvImportException.Unreadable(e)
        }

        if (copied <= 0L) {
            target.delete()
            throw CvImportException.Unreadable()
        }

        StoredCvFile(
            displayName = displayName.ifBlank { "cv.${fileType.extensions.first()}" },
            storedName = storedName,
            fileType = fileType,
            sizeBytes = copied,
            file = target,
        )
    }

    /** Removes a previously stored file, ignoring the case where it is already gone. */
    fun delete(storedName: String) {
        runCatching { File(directory, storedName).delete() }
    }

    fun exists(storedName: String): Boolean = File(directory, storedName).isFile

    fun open(storedName: String): File = File(directory, storedName)

    /** Reads display name and size from the picker without opening the stream. */
    private fun readMetadata(uri: Uri): Pair<String, Long> {
        var name = uri.lastPathSegment?.substringAfterLast('/') ?: ""
        var size = 0L
        try {
            context.contentResolver.query(uri, null, null, null, null)?.use { cursor ->
                if (cursor.moveToFirst()) {
                    val nameIndex = cursor.getColumnIndex(OpenableColumns.DISPLAY_NAME)
                    val sizeIndex = cursor.getColumnIndex(OpenableColumns.SIZE)
                    if (nameIndex >= 0 && !cursor.isNull(nameIndex)) name = cursor.getString(nameIndex)
                    if (sizeIndex >= 0 && !cursor.isNull(sizeIndex)) size = cursor.getLong(sizeIndex)
                }
            }
        } catch (_: Exception) {
            // Some providers do not expose metadata; the extension check still applies.
        }
        return name to size
    }

    companion object {
        private const val DIRECTORY = "cv_documents"

        /** 15 MB is far beyond any real CV and keeps memory use predictable. */
        const val MAX_BYTES = 15L * 1024 * 1024
    }
}

/** Why an import was rejected, phrased for the user. */
sealed class CvImportException(message: String, cause: Throwable? = null) : Exception(message, cause) {
    class UnsupportedFormat(val fileName: String) :
        CvImportException("This file type is not supported. Choose a PDF, DOC, DOCX or TXT file.")

    class TooLarge(val sizeBytes: Long, val limitBytes: Long) :
        CvImportException("This file is larger than the 15 MB limit.")

    class Unreadable(cause: Throwable? = null) :
        CvImportException("The file could not be read from your device.", cause)
}
